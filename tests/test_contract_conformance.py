"""F-2: the visualizer can display everything in the vendored pipeline contract.

The contract (``mailroom_ui/contract/mailroom-contract.json``) is generated by
llm-mailroom (ADR-001) and vendored by ``scripts/bump_producer_pin.py``. These
tests fail when the pipeline adds, renames or removes a node, span, agent,
class or read score that the visualizer has not been taught about.
"""

from __future__ import annotations

import copy
import json
import re
from pathlib import Path

import pytest

from mailroom_ui import pipeline_schema as ps
from mailroom_ui.models import Stage

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "mailroom_ui" / "contract" / "source.json"


def test_vendored_contract_is_conformant():
    assert ps.contract_gaps() == []


def test_contract_provenance_is_recorded():
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    assert re.fullmatch(r"[0-9a-f]{40}", source["pipeline_commit"])
    assert source["contract_version"] == ps.CONTRACT["contract_version"]
    assert source["pipeline_version"] == ps.CONTRACT["pipeline_version"]
    # A contract from another commit than the pin must say why.
    if not source["matches_pin"]:
        assert source.get("note"), "provisional contract needs a provenance note"


def test_renamed_span_is_a_gap():
    contract = copy.deepcopy(ps.CONTRACT)
    contract["spans"]["classify-documents"] = contract["spans"].pop("classify-document")
    for node in contract["graph"]["nodes"]:
        if node["span"] == "classify-document":
            node["span"] = "classify-documents"
    gaps = ps.contract_gaps(contract)
    assert any("'classify-documents' has no floor stage" in g for g in gaps)
    assert any("'classify-document' no longer exists" in g for g in gaps)


def test_new_node_agent_score_and_failure_class_are_gaps():
    contract = copy.deepcopy(ps.CONTRACT)
    contract["graph"]["nodes"].append(
        {"id": "score_document", "span": "score-document", "observation_type": "evaluator"}
    )
    contract["agents"].append("scorer")
    contract["failure_classes"].append("audit_failed")
    contract["scores"]["configs"] = [
        c for c in contract["scores"]["configs"] if c["name"] != "total_tokens"
    ]
    gaps = "\n".join(ps.contract_gaps(contract))
    assert "graph node 'score_document' has no floor stage" in gaps
    assert "agent 'scorer' has no display label" in gaps
    assert "score 'total_tokens' is read by the visualizer" in gaps
    assert "failure class 'audit_failed' has no label" in gaps
    # ...but it still renders with a derived label meanwhile.
    assert ps.FAILURE_CLASS_LABELS.get("llm_timeout") == "LLM timeout"


def test_data_comes_from_the_contract():
    contract = ps.CONTRACT
    assert ps.LIVE_DOC_TYPES == tuple(dc["key"] for dc in contract["doc_classes"])
    assert set(ps.AGENTS) == set(contract["agents"])
    assert ps.FAILURE_CLASSES == tuple(contract["failure_classes"])
    for dc in contract["doc_classes"]:
        assert ps.SPECIALIST_BY_DOC_CLASS[dc["key"]] == dc["specialist"]
        assert ps.EXTRACTION_FIELD_KEYS_BY_CLASS[dc["key"]] == frozenset(dc["fields"])
        assert ps.DOC_SUBCLASS_BY_CLASS[dc["key"]] == tuple(dc["subclasses"])
    for span, kind in contract["spans"].items():
        assert ps.observation_type_for(span) == kind
    schema = ps.PipelineSchema()
    assert schema.confidence_high == contract["confidence"]["high"]
    assert schema.judge_max_passes == contract["confidence"]["judge_max_passes"]


def test_graph_nodes_report_their_observation_type():
    for node in ps.CONTRACT["graph"]["nodes"]:
        if node["observation_type"] in {"agent", "evaluator"}:
            assert ps.observation_type_for(node["id"]) == node["observation_type"]


def test_classification_arbiter_has_a_station():
    assert ps.SPAN_STAGE_MAP["classification_arbiter"] is Stage.RETRY_CLASSIFY
    assert ps.SPAN_STAGE_MAP["arbitrate-classification"] is Stage.RETRY_CLASSIFY


def test_unsupported_contract_major_is_refused(tmp_path):
    bad = dict(ps.CONTRACT, contract_version="2.0.0")
    path = tmp_path / "contract.json"
    path.write_text(json.dumps(bad), encoding="utf-8")
    with pytest.raises(RuntimeError, match="major 1"):
        ps.load_contract(path)


def _js_object(path: Path, name: str) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    body = re.search(rf"const {name} = \{{(.*?)\n  \}};", text, re.S)
    assert body, f"{name} not found in {path}"
    pairs = re.findall(r'"?([\w.-]+)"?\s*:\s*"([\w-]+)"', body.group(1))
    return dict(pairs)


def test_hosted_floor_maps_every_contract_span_and_node():
    """The Observatory keeps its own span table for live envelopes."""
    hosted = _js_object(ROOT / "hosted" / "js" / "app.js", "SPAN_STAGE")
    names = set(ps.CONTRACT["spans"]) | {n["id"] for n in ps.CONTRACT["graph"]["nodes"]}
    missing = sorted(n for n in names - set(hosted) if n not in ps.NON_STATION_SPANS)
    assert missing == []
